export interface PromptParams {
  majorGenre: string;
  minorGenre: string;
  answerFormat: string;
  wikipediaContext?: string;
}

const PROCEDURE_TEXT = `# 手順

1. 指定されたジャンルと答えの形式を元に、クイズの答えとしてふさわしいであろう単語を列挙する。
2. 手順1で生成した単語をもとに、30文字程度の長さのクイズの問題文と答えの案を考える。
  * この手順では、問題文の長さは30文字ちょうどである必要はありません。
  * 1つの単語について、複数の切り口から異なる問題文をいくつか生成してください。
  * 手順1で生成した単語が答えではないものの、それに関連したクイズの問題文も生成してください。
3. 手順2で生成した各問題文の表現を少しずつ変えたバリエーションを複数生成する。
  * 句読点を変えたり、語順を入れ替えたりするなどして、同じ内容のクイズでも異なる表現のものが生成されるようにしてください。
  * クイズの問題文として自然な日本語とすることを優先し、不自然な日本語になる場合は候補から外してください。
  * 問題文の文末に「〇〇は何？」「〇〇は誰？」「○○はどこ？」といった言い回しを使用しないでください。これらの代わりに「〇〇は？」といった形式を使用してください。
4. 手順3で生成したクイズの問題文について、問題文の長さを確認する。
  * 問題文の長さには、文末の疑問符も含めてください。
  * **文字数のカウントには必ず count_characters ツールを使用し、手動でのカウントは行わないでください。**
5. 手順4でカウントされた問題文の長さをもとに、問題文がちょうど30文字のものを選択する。
  * 可能であれば、文字数が30文字に近いものに対して修正を加えて、30文字に近づけることも検討してください。ただし、修正に際してはクイズの問題文として自然な日本語とすることを優先するものとし、修正を行うことで不自然な日本語になる場合は無理に修正しないでください。必要な助詞を削除したり、不要な助詞を加えるなどの変更は行わないでください。**修正された問題文も必ず count_characters ツールを使用して文字数のカウントを行い、文字数がちょうど30文字であることを確認してください。**
6. 生成されたクイズうち、問題文がちょうど30文字のものを選択し、それらの問題文と答えを、以下のTSV形式のコードブロックでまとめてください。

\`\`\`tsv
問題文\t答え
（ここに各クイズを1行ずつ記述）
\`\`\``;

export function buildPrompt(params: PromptParams): string {
  const wikiSection = params.wikipediaContext
    ? `\n# 参考情報\n\n以下のWikipedia記事を参考にして問題を作成してください。記事に記載されている固有名詞や事実を活用してください。\n\n${params.wikipediaContext.slice(0, 3000)}\n`
    : '';

  return `あなたにはこれから、指定されたジャンルと答えの形式に則った、問題文の長さが30文字のクイズをなるべく多く生成してもらいます。生成は必ず次の手順に従って行うものとし、手順を省略したり、手順に従わないクイズを生成したりしないでください。

# 指定内容

* 大ジャンル: ${params.majorGenre}
* 小ジャンル: ${params.minorGenre}
* 答えの形式: ${params.answerFormat}
${wikiSection}
${PROCEDURE_TEXT}
`;
}
